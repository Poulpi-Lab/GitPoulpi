//! Translated `--help` (`gitpoulpi -l fr --help`).
//!
//! The English doc comments on the clap tree stay the single source: they are
//! also the MCP tool descriptions, which therefore never change. A translation
//! is applied to a *copy* of the tree, only when `-l`/`--lang` is on the command
//! line (the environment is deliberately not consulted, so scripts and agents
//! get stable English output). Only explanations are swapped; command and flag
//! names, value names and possible values are never touched.
//!
//! Catalogs: `locales/help/<lang>.toml`, a flat table keyed by
//! [`HelpKey`]s (see [`help_keys`]) plus four `_`-prefixed heading entries.
//! A key missing from a catalog shows English; a language without a catalog
//! (not shipped yet) shows English with a warning on stderr.

use std::collections::HashMap;

use clap::{Arg, ArgAction, Command, CommandFactory, FromArgMatches};
use gitpoulpi_i18n::Lang;

/// Section-heading entries every catalog carries.
pub const HEADING_KEYS: [&str; 6] = [
    "_usage",
    "_options",
    "_arguments",
    "_commands",
    "_help_flag",
    "_version_flag",
];

/// One translatable help string: its catalog key and English source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HelpKey {
    pub key: String,
    pub english: String,
}

fn cmd_key(path: &[String]) -> String {
    if path.is_empty() {
        "gitpoulpi".to_string()
    } else {
        path.join(" ")
    }
}

/// Every translatable string of the tree, in a stable order. Keys: the command
/// path (`branch create`; root is `gitpoulpi`) for `about`, `<path>#long` for
/// `long_about`, `<path> --<arg id>` for an argument's help (`#long` for its
/// long help).
pub fn help_keys(root: &Command) -> Vec<HelpKey> {
    let mut out = Vec::new();
    collect(root, &mut Vec::new(), &mut out);
    out
}

fn collect(cmd: &Command, path: &mut Vec<String>, out: &mut Vec<HelpKey>) {
    let key = cmd_key(path);
    let mut push = |k: String, v: Option<String>| {
        if let Some(v) = v {
            out.push(HelpKey { key: k, english: v });
        }
    };
    push(key.clone(), cmd.get_about().map(|s| s.to_string()));
    push(
        format!("{key}#long"),
        cmd.get_long_about().map(|s| s.to_string()),
    );
    for arg in cmd.get_arguments() {
        if arg.is_hide_set() {
            continue;
        }
        let id = arg.get_id().as_str();
        push(
            format!("{key} --{id}"),
            arg.get_help().map(|s| s.to_string()),
        );
        push(
            format!("{key} --{id}#long"),
            arg.get_long_help().map(|s| s.to_string()),
        );
    }
    for sub in cmd.get_subcommands() {
        if sub.is_hide_set() {
            continue;
        }
        path.push(sub.get_name().to_string());
        collect(sub, path, out);
        path.pop();
    }
}

/// The help catalog text of `lang`: generated by `build.rs` with an
/// `include_str!` for each language built into this binary (the `lang-*`
/// features of `gitpoulpi-i18n`). English, the pseudo-locale and an unbuilt
/// language have none.
fn catalog_source(lang: Lang) -> Option<&'static str> {
    #[allow(unreachable_code)]
    Some(include!(concat!(env!("OUT_DIR"), "/help_catalogs.rs")))
}

/// The catalog of `lang`, `None` for English or a language without one.
pub fn catalog(lang: Lang) -> Option<HashMap<String, String>> {
    let src = catalog_source(lang)?;
    let table: toml::Table = src.parse().expect("help catalog is valid TOML");
    Some(
        table
            .into_iter()
            .filter_map(|(k, v)| v.as_str().map(|s| (k, s.to_string())))
            .collect(),
    )
}

/// Returns `root` with every explanation replaced by its `lang` translation.
pub fn translate_command(root: Command, lang: Lang) -> Command {
    let Some(cat) = catalog(lang) else {
        return root;
    };
    let heading = |k: &str, fallback: &str| cat.get(k).cloned().unwrap_or_else(|| fallback.into());
    let h = Headings {
        usage: heading("_usage", "Usage:"),
        options: leak(heading("_options", "Options")),
        arguments: leak(heading("_arguments", "Arguments")),
        commands: leak(heading("_commands", "Commands")),
        help_flag: heading("_help_flag", "Print help (see more with '--help')"),
        version_flag: heading("_version_flag", "Print version"),
    };
    let mut root = tr(root, &mut Vec::new(), &cat, &h, true);
    root = root.disable_version_flag(true).arg(
        Arg::new("version")
            .short('V')
            .long("version")
            .action(ArgAction::Version)
            .help(h.version_flag.clone())
            .help_heading(h.options),
    );
    root
}

/// clap headings are `&'static str`; a handful of short strings, once per process.
fn leak(s: String) -> &'static str {
    Box::leak(s.into_boxed_str())
}

struct Headings {
    usage: String,
    options: &'static str,
    arguments: &'static str,
    commands: &'static str,
    help_flag: String,
    version_flag: String,
}

fn tr(
    mut cmd: Command,
    path: &mut Vec<String>,
    cat: &HashMap<String, String>,
    h: &Headings,
    is_root: bool,
) -> Command {
    let key = cmd_key(path);
    if let Some(t) = cat.get(&key) {
        cmd = cmd.about(t.clone());
    }
    if let Some(t) = cat.get(&format!("{key}#long")) {
        cmd = cmd.long_about(t.clone());
    }
    let ids: Vec<(String, bool)> = cmd
        .get_arguments()
        .map(|a| (a.get_id().as_str().to_string(), a.is_positional()))
        .collect();
    for (id, positional) in ids {
        let (help, long) = (
            cat.get(&format!("{key} --{id}")).cloned(),
            cat.get(&format!("{key} --{id}#long")).cloned(),
        );
        let heading = if positional { h.arguments } else { h.options };
        cmd = cmd.mut_arg(id, move |mut a| {
            if let Some(t) = help {
                a = a.help(t);
            }
            if let Some(t) = long {
                a = a.long_help(t);
            }
            a.help_heading(heading)
        });
    }
    let names: Vec<String> = cmd
        .get_subcommands()
        .map(|s| s.get_name().to_string())
        .collect();
    for name in names {
        path.push(name.clone());
        cmd = cmd.mut_subcommand(name, |sub| tr(sub, path, cat, h, false));
        path.pop();
    }
    let _ = is_root;
    cmd.disable_help_flag(true)
        .arg(
            Arg::new("help")
                .short('h')
                .long("help")
                .action(ArgAction::Help)
                .global(false)
                .help(h.help_flag.clone())
                .help_heading(h.options),
        )
        .subcommand_help_heading(h.commands)
        .help_template(format!(
            "{{before-help}}{{about-with-newline}}\n{} {{usage}}\n\n{{all-args}}{{after-help}}",
            h.usage
        ))
}

/// Pre-scans argv for `-l X`, `-lX`, `--lang X`, `--lang=X` (stopping at `--`).
/// `Err` carries the offending value.
pub fn prescan_lang<I, S>(args: I) -> Result<Option<Lang>, String>
where
    I: IntoIterator<Item = S>,
    S: AsRef<str>,
{
    let args: Vec<String> = args.into_iter().map(|s| s.as_ref().to_string()).collect();
    let mut found = None;
    let mut i = 1;
    while i < args.len() {
        let a = args[i].as_str();
        let value = if a == "--" {
            break;
        } else if a == "-l" || a == "--lang" {
            i += 1;
            args.get(i).cloned()
        } else if let Some(v) = a.strip_prefix("--lang=") {
            Some(v.to_string())
        } else {
            a.strip_prefix("-l")
                .filter(|v| !v.is_empty())
                .map(|v| v.trim_start_matches('=').to_string())
        };
        if let Some(v) = value {
            match Lang::parse(&v) {
                Some(l) if l != Lang::Qps => found = Some(l),
                _ => return Err(v),
            }
        }
        i += 1;
    }
    Ok(found)
}

/// `undo restore <id>` and `reflog restore <ref> <oid>` are spelled as
/// two words but are the commands `undo-restore` and `reflog-restore`:
/// `undo` and `reflog` are tools of their own, and a command with
/// subcommands cannot be one. (A branch named `restore` is read with
/// `gitpoulpi reflog refs/heads/restore`.)
pub fn spell_aliases(args: Vec<String>) -> Vec<String> {
    let mut out: Vec<String> = Vec::with_capacity(args.len());
    let mut i = 0;
    while i < args.len() {
        let joined = match (args[i].as_str(), args.get(i + 1).map(String::as_str)) {
            ("undo", Some("restore")) => Some("undo-restore"),
            ("reflog", Some("restore")) => Some("reflog-restore"),
            _ => None,
        };
        match joined {
            Some(name) => {
                out.push(name.to_string());
                i += 2;
            }
            None => {
                out.push(args[i].clone());
                i += 1;
            }
        }
    }
    out
}

/// `Cli::parse()`, with the help text translated when `-l` is given.
pub fn parse_localized() -> super::Cli {
    let mut cmd = super::Cli::command();
    match prescan_lang(std::env::args()) {
        Ok(Some(lang)) if lang != Lang::En => {
            if catalog(lang).is_none() {
                eprintln!(
                    "gitpoulpi: no translated help for '{}' (not built into this binary, or not shipped yet); showing English.",
                    lang.code()
                );
            } else {
                cmd = translate_command(cmd, lang);
            }
        }
        Ok(_) => {}
        Err(bad) => {
            eprintln!(
                "gitpoulpi: invalid value '{bad}' for --lang (expected one of: {})",
                gitpoulpi_i18n::SHIPPED
                    .iter()
                    .map(|l| l.code())
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            std::process::exit(2);
        }
    }
    let mut matches = cmd.get_matches_from(spell_aliases(std::env::args().collect()));
    match super::Cli::from_arg_matches_mut(&mut matches) {
        Ok(cli) => cli,
        Err(e) => e.exit(),
    }
}
