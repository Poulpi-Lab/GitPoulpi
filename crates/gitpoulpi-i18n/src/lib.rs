/// A plain (placeholder-free, non-plural) message id. `Copy`, `const`
/// constructible through [`msg`], so static tables of labels stay `const`.
/// Long-lived state stores the `M`, never the resolved string.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct M(pub(crate) u16);

impl M {
    /// The text in the current language and vocabulary. `&'static`, no
    /// allocation.
    #[inline]
    pub fn get(self) -> &'static str {
        let (lang, variant) = state();
        self.at(lang, variant)
    }

    /// The text in `lang`, current vocabulary (e.g. the English label for
    /// bilingual search).
    pub fn get_in(self, lang: Lang) -> &'static str {
        self.at(lang.index(), state().1)
    }

    /// The English text, current vocabulary.
    pub fn english(self) -> &'static str {
        self.get_in(Lang::En)
    }

    #[inline]
    fn at(self, lang: usize, variant: usize) -> &'static str {
        let base = (self.0 & 0x7fff) as usize;
        let off = if self.0 & 0x8000 != 0 { variant } else { 0 };
        generated::string(generated::PLAIN[generated::LANG_ROW[lang] as usize][base + off] as usize)
    }
}

impl Display for M {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.get())
    }
}

/// `map` holds alternative ids (see `generated::alt`), indexed by
/// `(row * 8 + variant) * 4 + form`, `row` being `LANG_ROW[lang]`.
pub(crate) struct ArgMsg {
    pub map: [u16; generated::BUILT_LANGS * 32],
}

fn render(segs: &[u32], args: &[&dyn Display]) -> String {
    let cap = segs
        .iter()
        .map(|&s| {
            if s & 1 == 0 {
                generated::string((s >> 1) as usize).len()
            } else {
                8
            }
        })
        .sum();
    let mut out = String::with_capacity(cap);
    for &s in segs {
        if s & 1 == 0 {
            out.push_str(generated::string((s >> 1) as usize));
        } else {
            let _ = write!(out, "{}", args[(s >> 1) as usize]);
        }
    }
    out
}

pub(crate) fn format_arg(m: &ArgMsg, n: Option<u64>, args: &[&dyn Display]) -> String {
    let (lang, variant) = state();
    let form = n.map_or(0, |n| Lang::ALL[lang].plural_form(n) as usize);
    let row = generated::LANG_ROW[lang] as usize;
    let id = m.map[(row * 8 + variant) * 4 + form] as usize;
    render(generated::alt(id), args)
}

