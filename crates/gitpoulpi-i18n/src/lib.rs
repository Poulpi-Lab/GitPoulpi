/// Languages whose catalog is complete **and built into this binary**, in
/// picker order; the Settings picker lists these. Generated by `build.rs`
/// (complete catalogs, i.e. `MISSING` holds no entry for them, that the
/// `lang-*` features selected). English is always first.
pub use generated::SHIPPED;

/// CLDR plural category for an integer count (`many` only concerns compact
/// decimals, which are never printed).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Plural {
    One = 0,
    Other = 1,
    Few = 2,
    Many = 3,
}

const _: () = assert!(generated::LANG_ROW.len() == Lang::ALL.len());

impl Lang {
    /// Languages whose git vocabulary may be forced back to English words
    /// (`ui.git_terms_english`): transliterating or translated scripts.
    pub const fn has_english_git_option(self) -> bool {
        matches!(self, Lang::ZhCn | Lang::Ja | Lang::Ko)
    }

    pub const ALL: [Lang; 18] = [
        Lang::En,
        Lang::Fr,
        Lang::Es,
        Lang::PtBr,
        Lang::PtPt,
        Lang::It,
        Lang::De,
        Lang::ZhCn,
        Lang::Ja,
        Lang::Ru,
        Lang::Ko,
        Lang::Nl,
        Lang::Pl,
        Lang::Uk,
        Lang::Cs,
        Lang::Sv,
        Lang::Tr,
        Lang::Qps,
    ];

    #[inline]
    const fn index(self) -> usize {
        self as usize
    }

    /// BCP 47 tag, also the `GITPOULPI_LANG` / `-l` value and the file stem.
    pub const fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::PtBr => "pt-BR",
            Lang::PtPt => "pt-PT",
            Lang::It => "it",
            Lang::De => "de",
            Lang::ZhCn => "zh-CN",
            Lang::Ja => "ja",
            Lang::Ru => "ru",
            Lang::Ko => "ko",
            Lang::Nl => "nl",
            Lang::Pl => "pl",
            Lang::Uk => "uk",
            Lang::Cs => "cs",
            Lang::Sv => "sv",
            Lang::Tr => "tr",
            Lang::Qps => "qps",
        }
    }

    /// The language's own name (`_meta.language_name`), for the picker.
    pub fn native_name(self) -> &'static str {
        generated::LANG_NAMES[self.index()]
    }

    /// Whether this language's catalog is compiled into this binary. English
    /// always is; the others follow the `lang-*` cargo features. An unbuilt
    /// language still parses (config values and `-l xx` keep working) and
    /// resolves to English text.
    pub const fn is_built(self) -> bool {
        self.index() == 0 || generated::LANG_ROW[self.index()] != 0
    }

    pub fn is_shipped(self) -> bool {
        SHIPPED.contains(&self)
    }

    /// Plural category for an integer `n` (CLDR). en/es/it/de/pt-PT/nl/sv/tr:
    /// one iff n = 1; fr/pt-BR: one iff n is 0 or 1; ja/zh/ko: always other;
    /// ru/uk: one (n%10=1, n%100!=11), few (n%10 in 2..4, n%100 not 12..14),
    /// else many; pl: one iff n = 1, few as ru, else many; cs: one iff n = 1,
    /// few for 2..4, else other.
    pub const fn plural_form(self, n: u64) -> Plural {
        let (m10, m100) = (n % 10, n % 100);
        let slavic_few = m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14);
        match self {
            Lang::ZhCn | Lang::Ja | Lang::Ko => Plural::Other,
            Lang::Fr | Lang::PtBr => {
                if n <= 1 {
                    Plural::One
                } else {
                    Plural::Other
                }
            }
            Lang::Ru | Lang::Uk => {
                if m10 == 1 && m100 != 11 {
                    Plural::One
                } else if slavic_few {
                    Plural::Few
                } else {
                    Plural::Many
                }
            }
            Lang::Pl => {
                if n == 1 {
                    Plural::One
                } else if slavic_few {
                    Plural::Few
                } else {
                    Plural::Many
                }
            }
            Lang::Cs => {
                if n == 1 {
                    Plural::One
                } else if n >= 2 && n <= 4 {
                    Plural::Few
                } else {
                    Plural::Other
                }
            }
            _ => {
                if n == 1 {
                    Plural::One
                } else {
                    Plural::Other
                }
            }
        }
    }

    /// Parses a user-supplied language: `fr`, `fr_CA.UTF-8`, `pt-BR`,
    /// `pt_PT`, `DE`, `qps`. Bare `pt` is Brazilian; the European regions
    /// (PT, AO, MZ, ...) give pt-PT. `C`/`POSIX`/unknown give `None`.
    pub fn parse(s: &str) -> Option<Lang> {
        let s = s
            .trim()
            .split(['.', '@'])
            .next()
            .unwrap_or("")
            .replace('_', "-");
        let s = s.to_ascii_lowercase();
        let mut parts = s.split('-');
        let primary = parts.next()?;
        let region = parts.find(|p| p.len() == 2);
        Some(match primary {
            "en" => Lang::En,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "it" => Lang::It,
            "de" => Lang::De,
            "ja" => Lang::Ja,
            "ru" => Lang::Ru,
            "ko" => Lang::Ko,
            "nl" => Lang::Nl,
            "pl" => Lang::Pl,
            "uk" => Lang::Uk,
            "cs" => Lang::Cs,
            "sv" => Lang::Sv,
            "tr" => Lang::Tr,
            // Simplified Chinese only: zh-Hant, zh-TW/HK/MO are not supported.
            "zh" => {
                if s.contains("-hant") || matches!(region, Some("tw" | "hk" | "mo")) {
                    return None;
                }
                Lang::ZhCn
            }
            "qps" => Lang::Qps,
            "pt" => match region {
                Some(
                    "pt" | "ao" | "cv" | "gw" | "mo" | "mz" | "st" | "tl" | "gq" | "ch" | "lu",
                ) => Lang::PtPt,
                _ => Lang::PtBr,
            },
            _ => return None,
        })
    }

    /// Alias of [`Lang::parse`] for locale strings from the OS.
    pub fn from_bcp47(s: &str) -> Option<Lang> {
        Lang::parse(s)
    }
}

// ---------------------------------------------------------------- state

static LANG: AtomicU8 = AtomicU8::new(0);
static TRANSLATE_GIT: AtomicBool = AtomicBool::new(false);
static MERGE_HOST: AtomicBool = AtomicBool::new(false);
static ENGLISH_GIT: AtomicBool = AtomicBool::new(false);
static EPOCH: AtomicU64 = AtomicU64::new(0);

const NONE: u8 = 255;

struct Override {
    lang: Cell<u8>,
    /// 0 = none, 1 = off, 2 = on.
    git: Cell<u8>,
    merge: Cell<u8>,
    english: Cell<u8>,
    epoch: Cell<u64>,
}

thread_local! {
    /// Per-thread override, for tests: parallel tests never see each
    /// other's language, and a test that sets nothing gets English.
    static OVERRIDE: Override = const {
        Override { lang: Cell::new(NONE), git: Cell::new(0), merge: Cell::new(0), english: Cell::new(0), epoch: Cell::new(0) }
    };
}

/// (language index, variant). Variant bit 1 = translated git vocabulary,
/// bit 0 = the linked host says "merge request", bit 2 = git words forced to
/// English (only ever set for ja, ko and zh-CN, with bit 1 clear).
#[inline]
fn state() -> (usize, usize) {
    OVERRIDE.with(|o| {
        let lang = match o.lang.get() {
            NONE => LANG.load(Relaxed),
            v => v,
        };
        let git = match o.git.get() {
            0 => TRANSLATE_GIT.load(Relaxed),
            v => v == 2,
        };
        let merge = match o.merge.get() {
            0 => MERGE_HOST.load(Relaxed),
            v => v == 2,
        };
        let english = match o.english.get() {
            0 => ENGLISH_GIT.load(Relaxed),
            v => v == 2,
        };
        let forced = english && !git && Lang::ALL[lang as usize].has_english_git_option();
        (
            lang as usize,
            (usize::from(forced) << 2) | (usize::from(git) << 1) | usize::from(merge),
        )
    })
}

/// The effective display language.
pub fn current() -> Lang {
    Lang::ALL[state().0]
}

/// Whether git terms use the translated vocabulary (`false`: English).
pub fn git_terms_translated() -> bool {
    state().1 & 2 != 0
}

/// Whether the English git words are forced (ja, ko, zh-CN with the option on
/// and the translated vocabulary off).
pub fn git_terms_forced_english() -> bool {
    state().1 & 4 != 0
}

/// Whether PR text says "merge request" (the linked host is GitLab).
pub fn merge_terms() -> bool {
    state().1 & 1 != 0
}

/// Production switch (Settings, `GITPOULPI_LANG`). Bumps [`epoch`] on change.
pub fn set(lang: Lang) {
    if LANG.swap(lang as u8, Relaxed) != lang as u8 {
        EPOCH.fetch_add(1, Relaxed);
    }
}

/// The "Translate git terms" setting (default off).
pub fn set_translate_git_terms(on: bool) {
    if TRANSLATE_GIT.swap(on, Relaxed) != on {
        EPOCH.fetch_add(1, Relaxed);
    }
}

/// The "English git words" setting (`ui.git_terms_english`, default off). It
/// only acts in languages where [`Lang::has_english_git_option`] holds.
pub fn set_english_git_terms(on: bool) {
    if ENGLISH_GIT.swap(on, Relaxed) != on {
        EPOCH.fetch_add(1, Relaxed);
    }
}

/// `ui.pr_terminology` resolved: true when PR text says "merge request".
pub fn set_merge_terms(merge: bool) {
    if MERGE_HOST.swap(merge, Relaxed) != merge {
        EPOCH.fetch_add(1, Relaxed);
    }
}

/// Changes whenever the language or a term vocabulary changes (global
/// switches and this thread's overrides). Key caches of resolved text on it.
pub fn epoch() -> u64 {
    EPOCH.load(Relaxed) + OVERRIDE.with(|o| o.epoch.get())
}

#[derive(Clone, Copy)]
enum Slot {
    Lang,
    Git,
    Merge,
    English,
}

/// Restores the previous per-thread override on drop.
#[must_use = "the override ends when the guard is dropped"]
pub struct OverrideGuard {
    slot: Slot,
    prev: u8,
}

fn set_slot(slot: Slot, v: u8) -> u8 {
    OVERRIDE.with(|o| {
        let cell = match slot {
            Slot::Lang => &o.lang,
            Slot::Git => &o.git,
            Slot::Merge => &o.merge,
            Slot::English => &o.english,
        };
        o.epoch.set(o.epoch.get() + 1);
        cell.replace(v)
    })
}

/// Test helper: this thread sees `lang` until the guard drops.
pub fn override_lang(lang: Lang) -> OverrideGuard {
    OverrideGuard {
        slot: Slot::Lang,
        prev: set_slot(Slot::Lang, lang as u8),
    }
}

/// Test helper: this thread sees the translated (or English) git vocabulary.
pub fn override_git_terms(translated: bool) -> OverrideGuard {
    OverrideGuard {
        slot: Slot::Git,
        prev: set_slot(Slot::Git, 1 + u8::from(translated)),
    }
}

/// Test helper: this thread sees the English git words forced (or not).
pub fn override_english_git_terms(on: bool) -> OverrideGuard {
    OverrideGuard {
        slot: Slot::English,
        prev: set_slot(Slot::English, 1 + u8::from(on)),
    }
}

/// Test helper: this thread sees "merge request" (or "pull request").
pub fn override_merge_terms(merge: bool) -> OverrideGuard {
    OverrideGuard {
        slot: Slot::Merge,
        prev: set_slot(Slot::Merge, 1 + u8::from(merge)),
    }
}

impl Drop for OverrideGuard {
    fn drop(&mut self) {
        set_slot(self.slot, self.prev);
    }
}

/// Runs `f` with `lang` as this thread's language.
pub fn with_lang<R>(lang: Lang, f: impl FnOnce() -> R) -> R {
    let _g = override_lang(lang);
    f()
}

