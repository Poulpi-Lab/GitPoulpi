#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_languages() {
        assert_eq!(Lang::parse("fr_CA.UTF-8"), Some(Lang::Fr));
        assert_eq!(Lang::parse("de_CH.UTF-8"), Some(Lang::De));
        assert_eq!(Lang::parse("pt"), Some(Lang::PtBr));
        assert_eq!(Lang::parse("pt_BR"), Some(Lang::PtBr));
        assert_eq!(Lang::parse("pt-PT"), Some(Lang::PtPt));
        assert_eq!(Lang::parse("pt_AO.UTF-8"), Some(Lang::PtPt));
        assert_eq!(Lang::parse("QPS"), Some(Lang::Qps));
        assert_eq!(Lang::parse("C"), None);
        assert_eq!(Lang::parse("POSIX"), None);
        assert_eq!(Lang::parse(""), None);
        // Every language parses, built or not.
        for l in Lang::ALL {
            assert_eq!(Lang::parse(l.code()), Some(l));
        }
    }

    #[test]
    fn english_is_always_built_and_shipped_is_built() {
        assert!(Lang::En.is_built());
        assert_eq!(SHIPPED[0], Lang::En);
        for l in SHIPPED {
            assert!(l.is_built(), "{l:?}");
        }
        for l in Lang::ALL {
            // The built set is exactly what the tables know about.
            assert_eq!(
                l.is_built(),
                l == Lang::En || generated::LANG_ROW[l.index()] != 0
            );
        }
    }

    /// In a build without a language, its text is English (not a panic, not
    /// an empty string). With every language built there is nothing to check.
    #[test]
    fn unbuilt_language_reads_as_english() {
        for l in Lang::ALL.into_iter().filter(|l| !l.is_built()) {
            let _g = override_lang(l);
            assert_eq!(
                msg::month::JANUARY.get(),
                msg::month::JANUARY.english(),
                "{l:?}"
            );
            assert_eq!(current(), l);
        }
    }

    #[test]
    fn every_built_language_has_its_own_row() {
        let mut rows: Vec<u8> = Lang::ALL
            .into_iter()
            .filter(|l| l.is_built())
            .map(|l| generated::LANG_ROW[l.index()])
            .collect();
        rows.sort_unstable();
        assert_eq!(rows, (0..rows.len() as u8).collect::<Vec<_>>());
        assert_eq!(rows.len(), generated::BUILT_LANGS);
    }
}
