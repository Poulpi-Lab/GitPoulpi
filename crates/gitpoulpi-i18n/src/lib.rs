//! UI translations, compiled in. See `docs/developer/i18n.md`.
//!
//! # Cost model
//!
//! * `M::get()` on a plain label: one thread-local read, one atomic load and
//!   two array indexes. It returns `&'static str`: **no allocation, no
//!   hashing, no formatting**. Borrow it straight into a `Span`.
//! * A message with placeholders or a plural is a typed `fn` returning
//!   `String`: one `String::with_capacity` and pushes over pre-split
//!   segments. No parsing at run time. Call it where the state changes, not
//!   once per frame for unchanged state.
//! * [`epoch`] is one atomic load plus one thread-local read; key caches of
//!   resolved text on it.
//! * Switching language, git-term vocabulary or PR/MR host is a few atomic
//!   stores plus an epoch bump; nothing is re-parsed.
//!
//! A typo in a key is a compile error:
//!
//! ```compile_fail
//! let _ = gitpoulpi_i18n::msg::common::PUHS.get();
//! ```
//!
//! ```
//! use gitpoulpi_i18n::{msg, Lang};
//! // Git words stay English by default; the setting switches to French.
//! assert_eq!(gitpoulpi_i18n::with_lang(Lang::Fr, || msg::common::files_staged(2)), "2 fichiers staged");
//! let _t = gitpoulpi_i18n::override_git_terms(true);
//! assert_eq!(gitpoulpi_i18n::with_lang(Lang::Fr, || msg::common::files_staged(2)), "2 fichiers indexés");
//! ```
//!
//! Depends on nothing but `std` and the tiny `sys-locale`, so the TUI and the
//! CLI can both use it.

