#!/usr/bin/env python3
"""Regenerate crates/gitpoulpi-config/src/theme/terminalcolors_data.rs.

Source: https://terminalcolors.com/ (Alacritty TOML downloads,
https://terminalcolors.com/downloads/alacritty/<family>-<variant>.toml).
Each scheme belongs to its authors. Usage:

    python3 scripts/gen-terminalcolors.py [list.txt]

`list.txt` has one `family/variant` per line (default: the LIST below).
Downloads are cached in $TMPDIR/terminalcolors-cache.
"""
import os, sys, tempfile, tomllib, urllib.request

